"""The catalogue: a generated index of every hypothesis and where it stands on the claim ladder."""

from collections import Counter
from pathlib import Path
from typing import Any

from trading.research import ladder, registry
from trading.research.registry import FAMILIES
from trading.research.runs import load_runs
from trading.research.split import seal_record

CATALOGUE_FILE = "CATALOGUE.md"

_ORDER = (
    ladder.CONFIRMED,
    ladder.SUPPORTED,
    ladder.CANDIDATE,
    ladder.REGISTERED,
    ladder.NOT_REPLICATED,
    ladder.REFUTED,
    ladder.REJECTED,
)


def write_catalogue(records: Path) -> tuple[Path, dict[str, ladder.Standing]]:
    """Recompute every status, write it into each hypothesis file, and regenerate the catalogue."""
    hypotheses = registry.load_all(records)
    runs = load_runs(records)
    table = ladder.standings(hypotheses, runs)
    for standing in table.values():
        if standing.hypothesis.meta.get("status") != standing.status:
            standing.hypothesis = registry.set_field(standing.hypothesis, "status", standing.status)
    path = records / CATALOGUE_FILE
    path.write_text(render(records, table, runs), encoding="utf-8", newline="\n")
    return path, table


def render(records: Path, table: dict[str, ladder.Standing], runs: list[dict[str, Any]]) -> str:
    counts = Counter(standing.status for standing in table.values())
    by_origin = Counter(standing.hypothesis.origin for standing in table.values())
    seal = seal_record(records)
    lines = [
        "# Catalogue",
        "",
        "Generated by `uv run trading research catalogue` from `hypotheses/` and `runs/`. "
        "Do not edit by hand: change the records and regenerate.",
        "",
        f"**{len(table)} hypotheses**: "
        + (", ".join(f"{counts[status]} {status}" for status in _ORDER if counts[status]) or "none yet")
        + ".",
        "",
        f"False-discovery control at {ladder.FDR:.0%} (Benjamini-Hochberg): across the train "
        f"tests of all {by_origin['literature']} literature hypotheses, and separately across the "
        f"dev tests of all {by_origin['exploration']} exploration hypotheses. A hypothesis "
        "without a run counts as p = 1.",
        "",
        "Test seal: "
        + (
            f"opened {seal['opened_at']} for {', '.join(seal['finalists'])}."
            if seal
            else "closed. No test-period data has been used."
        ),
        "",
    ]
    for family in FAMILIES:
        members = [s for s in table.values() if s.hypothesis.family == family]
        lines += [f"## {family.capitalize()}", ""]
        if not members:
            lines += ["No hypotheses yet.", ""]
            continue
        lines += [
            "| id | hypothesis | origin | claim | status | train | train p | q | dev | dev p | dev at 2x cost | test | Skeptic | runs |",
            "|---|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---|---:|",
        ]
        for standing in sorted(members, key=lambda s: (_ORDER.index(s.status), s.hypothesis.id)):
            hypothesis = standing.hypothesis
            literature = hypothesis.origin == "literature"
            doubled = (standing.dev or {}).get("double_cost") or {}
            count = sum(1 for run in runs if run["hypothesis"] == hypothesis.id)
            cells = [
                f"[{hypothesis.id}](hypotheses/{hypothesis.path.name})",
                hypothesis.title,
                hypothesis.origin,
                hypothesis.claim,
                f"**{standing.status}**",
                _number(standing.train, "estimate"),
                _number(standing.train, "p_value"),
                _value(standing.q_value) if literature else "",
                _number(standing.dev, "estimate"),
                _number(standing.dev, "p_value")
                + (f" (q {_value(standing.q_value)})" if not literature and standing.dev else ""),
                _value(doubled.get("estimate")),
                _number(standing.test, "estimate"),
                (hypothesis.skeptic or {}).get("verdict", ""),
                str(count),
            ]
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
    lines += [
        "Estimates are in the unit each hypothesis declares (see its file). p-values are "
        "one-sided in the predicted direction.",
        "",
    ]
    return "\n".join(lines)


def _number(run: dict[str, Any] | None, key: str) -> str:
    return _value(run.get(key)) if run else ""


def _value(value: float | None) -> str:
    return "" if value is None else f"{value:.4f}"
